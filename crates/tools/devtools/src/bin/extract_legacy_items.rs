//! Binary to extract item definitions from the LCE reference source.

use anyhow::{Context, Result};
use clap::Parser;
use mclre_devtools::legacy_items::{parse_items, ItemParser};
use std::fs;
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(name = "extract-legacy-items", about = "Extract items from LCE reference")]
struct Args {
    /// Path to the reference LCE source directory (Minecraft.World)
    #[arg(long, default_value = "../../../reference/lce-141217/MinecraftConsoles-141217/Minecraft.World")]
    reference_dir: PathBuf,

    /// Output directory for generated TOML files
    #[arg(long, default_value = "../../../data/legacy")]
    output_dir: PathBuf,
}

fn main() -> Result<()> {
    let args = Args::parse();

    println!("Extracting items from: {:?}", args.reference_dir);
    println!("Output directory: {:?}", args.output_dir);

    // Read Item.cpp file
    let item_cpp = read_file(&args.reference_dir.join("Item.cpp"))?;

    // Parse items
    let items = parse_items(&item_cpp).map_err(|e| anyhow::anyhow!(e)).context("Failed to parse items")?;

    println!("Parsed {} items", items.len());

    // Create output directory
    fs::create_dir_all(&args.output_dir).context("Failed to create output directory")?;

    // Render TOML
    let toml = render_items_toml(&items, "LCE reference");

    // Write output
    let output_path = args.output_dir.join("items.toml");
    fs::write(&output_path, toml).context("Failed to write items.toml")?;
    println!("Written to: {:?}", output_path);

    // Also write JSON
    let json_path = args.output_dir.join("items.json");
    let json = serde_json::to_string_pretty(&items).context("Failed to serialize JSON")?;
    fs::write(&json_path, json).context("Failed to write items.json")?;
    println!("Written to: {:?}", json_path);

    Ok(())
}

fn read_file(path: &PathBuf) -> Result<String> {
    fs::read_to_string(path)
        .with_context(|| format!("Failed to read {:?}", path))
}

fn render_items_toml(items: &[mclre_devtools::legacy_items::LegacyItem], source_label: &str) -> String {
    let mut out = String::new();
    out.push_str("# Generated by `cargo run -p mclre-devtools --bin extract-legacy-items`.\n");
    out.push_str("# Do not edit by hand: regenerate from the reference source.\n");
    out.push_str(&format!("# Source: {source_label}\n"));
    out.push_str(&format!("\nitem_count = {}\n", items.len()));
    
    for item in items {
        out.push_str("\n[[item]]\n");
        out.push_str(&format!("id = {}\n", item.id));
        out.push_str(&format!("symbol = \"{}\"\n", item.symbol));
        out.push_str(&format!("name = \"{}\"\n", item.name));
        out.push_str(&format!("max_stack_size = {}\n", item.max_stack_size));
        out.push_str(&format!("max_damage = {}\n", item.max_damage));
        out.push_str(&format!("enchantable = {}\n", item.enchantable));
        if let Some(food) = &item.food {
            out.push_str("food = { ");
            out.push_str(&format!("nutrition = {}, saturation = {}, fast_eat = {}, meat = {}, always_edible = {} }},\n",
                food.nutrition, food.saturation, food.fast_eat, food.meat, food.always_edible));
        }
        if let Some(tool) = &item.tool {
            out.push_str("tool = { ");
            out.push_str(&format!("tier = \"{}\", max_damage = {}, mining_speed = {}, attack_damage = {}, harvest_level = {} }},\n",
                tool.tier, tool.max_damage, tool.mining_speed, tool.attack_damage, tool.harvest_level));
        }
        if let Some(armor) = &item.armor {
            out.push_str("armor = { ");
            out.push_str(&format!("type = \"{}\", max_damage = {}, protection = {}, toughness = {}, knockback_resistance = {}, material = \"{}\" }},\n",
                armor.armor_type, armor.max_damage, armor.protection, armor.toughness, armor.knockback_resistance, armor.material));
        }
        out.push_str(&format!("source_file = \"{}\"\n", item.source_file));
        out.push_str(&format!("source_line = {}\n", item.source_line));
    }
    out
}