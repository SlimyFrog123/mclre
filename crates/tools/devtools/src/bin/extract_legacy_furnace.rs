//! Binary to extract furnace recipes from the LCE reference source.

use anyhow::{Context, Result};
use clap::Parser;
use mclre_devtools::legacy_furnace::{parse_furnace_recipes, FurnaceRecipeParser};
use std::fs;
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(name = "extract-legacy-furnace", about = "Extract furnace recipes from LCE reference")]
struct Args {
    /// Path to the reference LCE source directory (Minecraft.World)
    #[arg(long, default_value = "../../../reference/lce-141217/MinecraftConsoles-141217/Minecraft.World")]
    reference_dir: PathBuf,

    /// Output directory for generated TOML files
    #[arg(long, default_value = "../../../data/legacy")]
    output_dir: PathBuf,
}

fn main() -> Result<()> {
    let args = Args::parse();

    println!("Extracting furnace recipes from: {:?}", args.reference_dir);
    println!("Output directory: {:?}", args.output_dir);

    // Read furnace recipes file
    let furnace_cpp = read_file(&args.reference_dir.join("FurnaceRecipes.cpp"))?;

    // Parse furnace recipes
    let recipes = parse_furnace_recipes(&furnace_cpp).map_err(|e| anyhow::anyhow!(e)).context("Failed to parse furnace recipes")?;

    println!("Parsed {} furnace recipes", recipes.len());

    // Create output directory
    fs::create_dir_all(&args.output_dir).context("Failed to create output directory")?;

    // Render TOML
    let toml = render_furnace_toml(&recipes, "LCE reference");

    // Write output
    let output_path = args.output_dir.join("furnace.toml");
    fs::write(&output_path, toml).context("Failed to write furnace.toml")?;
    println!("Written to: {:?}", output_path);

    // Also write JSON
    let json_path = args.output_dir.join("furnace.json");
    let json = serde_json::to_string_pretty(&recipes).context("Failed to serialize JSON")?;
    fs::write(&json_path, json).context("Failed to write furnace.json")?;
    println!("Written to: {:?}", json_path);

    Ok(())
}

fn read_file(path: &PathBuf) -> Result<String> {
    fs::read_to_string(path)
        .with_context(|| format!("Failed to read {:?}", path))
}

fn render_furnace_toml(recipes: &[mclre_devtools::legacy_furnace::LegacyFurnaceRecipe], source_label: &str) -> String {
    let mut out = String::new();
    out.push_str("# Generated by `cargo run -p mclre-devtools --bin extract-legacy-furnace`.\n");
    out.push_str("# Do not edit by hand: regenerate from the reference source.\n");
    out.push_str(&format!("# Source: {source_label}\n"));
    out.push_str(&format!("\nfurnace_recipe_count = {}\n", recipes.len()));
    
    for recipe in recipes {
        out.push_str("\n[[furnace_recipe]]\n");
        out.push_str(&format!("input = \"{}\"\n", recipe.input));
        out.push_str(&format!("output = \"{}\"\n", recipe.output));
        out.push_str(&format!("output_count = {}\n", recipe.output_count));
        out.push_str(&format!("output_damage = {}\n", recipe.output_damage));
        out.push_str(&format!("experience = {}\n", recipe.experience));
        out.push_str(&format!("source_file = \"{}\"\n", recipe.source_file));
        out.push_str(&format!("source_line = {}\n", recipe.source_line));
    }
    out
}